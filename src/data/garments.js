export const getGarmentsByShop = (shopId) =>
  GARMENTS.filter((g) => g.shopId === shopId);

export const getGarmentsByCategory = (categoryId) =>
  GARMENTS.filter((g) => g.category === categoryId);

export const getAvailableGarments = () =>
  GARMENTS.filter((g) => g.availability === "available");

export const searchGarments = (query, filters = {}) => {
  let results = [...GARMENTS];
  if (query) {
    const q = query.toLowerCase();
    results = results.filter(
      (g) =>
        g.name.toLowerCase().includes(q) ||
        g.category.toLowerCase().includes(q) ||
        g.occasion.some((o) => o.toLowerCase().includes(q)) ||
        g.colors.some((c) => c.toLowerCase().includes(q))
    );
  }
  if (filters.category) results = results.filter((g) => g.category === filters.category);
  if (filters.gender) results = results.filter((g) => g.gender === filters.gender);
  if (filters.size) results = results.filter((g) => g.sizes.includes(filters.size));
  if (filters.minPrice) results = results.filter((g) => g.rentalPrice >= filters.minPrice);
  if (filters.maxPrice) results = results.filter((g) => g.rentalPrice <= filters.maxPrice);
  if (filters.availability) results = results.filter((g) => g.availability === filters.availability);
  return results;
};
